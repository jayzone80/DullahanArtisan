/// Minimal zero-dependency 5x7 bitmap pixel font and 2D RGBA canvas helpers
/// shared across palette contact sheets, 3D render HUDs, and audio diagnostic plots.

pub struct Canvas {
    pub width: usize,
    pub height: usize,
    pub rgba: Vec<u8>,
}

impl Canvas {
    pub fn new(width: usize, height: usize, bg: [u8; 4]) -> Self {
        let mut rgba = vec![0u8; width * height * 4];
        for px in rgba.chunks_exact_mut(4) {
            px.copy_from_slice(&bg);
        }
        Self { width, height, rgba }
    }

    #[inline]
    pub fn set_px(&mut self, x: i32, y: i32, c: [u8; 4]) {
        if x < 0 || y < 0 || x >= self.width as i32 || y >= self.height as i32 {
            return;
        }
        let idx = (y as usize * self.width + x as usize) * 4;
        if c[3] == 255 {
            self.rgba[idx..idx + 4].copy_from_slice(&c);
        } else if c[3] > 0 {
            let a = c[3] as u32;
            let inv = 255 - a;
            self.rgba[idx] = ((c[0] as u32 * a + self.rgba[idx] as u32 * inv) / 255) as u8;
            self.rgba[idx + 1] = ((c[1] as u32 * a + self.rgba[idx + 1] as u32 * inv) / 255) as u8;
            self.rgba[idx + 2] = ((c[2] as u32 * a + self.rgba[idx + 2] as u32 * inv) / 255) as u8;
            self.rgba[idx + 3] = 255;
        }
    }

    pub fn fill_rect(&mut self, x: i32, y: i32, w: i32, h: i32, c: [u8; 4]) {
        let x0 = x.max(0);
        let y0 = y.max(0);
        let x1 = (x + w).min(self.width as i32);
        let y1 = (y + h).min(self.height as i32);
        for py in y0..y1 {
            for px in x0..x1 {
                self.set_px(px, py, c);
            }
        }
    }

    pub fn stroke_rect(&mut self, x: i32, y: i32, w: i32, h: i32, c: [u8; 4]) {
        self.fill_rect(x, y, w, 1, c);
        self.fill_rect(x, y + h - 1, w, 1, c);
        self.fill_rect(x, y, 1, h, c);
        self.fill_rect(x + w - 1, y, 1, h, c);
    }

    pub fn draw_line(&mut self, mut x0: i32, mut y0: i32, x1: i32, y1: i32, c: [u8; 4]) {
        let dx = (x1 - x0).abs();
        let sx = if x0 < x1 { 1 } else { -1 };
        let dy = -(y1 - y0).abs();
        let sy = if y0 < y1 { 1 } else { -1 };
        let mut err = dx + dy;
        loop {
            self.set_px(x0, y0, c);
            if x0 == x1 && y0 == y1 {
                break;
            }
            let e2 = 2 * err;
            if e2 >= dy {
                err += dy;
                x0 += sx;
            }
            if e2 <= dx {
                err += dx;
                y0 += sy;
            }
        }
    }

    pub fn draw_text(&mut self, mut x: i32, y: i32, text: &str, c: [u8; 4], scale: i32) {
        let scale = scale.max(1);
        for ch in text.chars() {
            let g = glyph(ch);
            for (row, &bits) in g.iter().enumerate() {
                for col in 0..5 {
                    if (bits & (1 << (4 - col))) != 0 {
                        self.fill_rect(
                            x + col * scale,
                            y + row as i32 * scale,
                            scale,
                            scale,
                            c,
                        );
                    }
                }
            }
            x += 6 * scale;
        }
    }
}

